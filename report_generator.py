"""
report_generator.py - PassGuard PDF security audit report
=========================================================

Builds a PDF (as bytes) from the NON-SENSITIVE analysis dictionary produced by
password_analyzer.analyze_password().

PRIVACY: this module never receives the password. The report, its metadata and the
suggested filename are built only from derived values (length, entropy, flags, ...).
"""

from __future__ import annotations

import io
from datetime import datetime
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import cm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from password_analyzer import ENTROPY_NOTE, SCORE_NOTE

STRENGTH_COLORS = {          # hex strings so they can be used inside Paragraph markup
    "Weak": "#c62828",
    "Moderate": "#ef6c00",
    "Strong": "#2e7d32",
    "Very Strong": "#00695c",
}
NAVY = colors.HexColor("#0b2545")

PRIVACY_NOTE = (
    "Privacy: the analyzed password was NOT stored, logged or included in this report. "
    "Only derived, non-sensitive values (length, character types, entropy estimate, detected "
    "weaknesses) appear here. Only fictional passwords should be analyzed with this tool."
)

LIMITATIONS = [
    SCORE_NOTE,
    ENTROPY_NOTE,
    "Detection uses a small starter list of common passwords and simple pattern rules; it "
    "cannot know whether a password has appeared in a real data breach.",
    "Character variety does not guarantee security. Long, unpredictable and unique passwords "
    "(ideally generated by a password manager) with multi-factor authentication are preferred.",
    "This report is for education and demonstration and is not a professional security audit.",
]


def build_report_filename(generated_at: datetime | None = None) -> str:
    """Filename based only on the time, e.g. PassGuard_Report_20260101_153000.pdf."""
    generated_at = generated_at or datetime.now()
    return f"PassGuard_Report_{generated_at.strftime('%Y%m%d_%H%M%S')}.pdf"


def _styles():
    base = getSampleStyleSheet()
    return {
        "title": ParagraphStyle("PGTitle", parent=base["Title"], textColor=NAVY, fontSize=22,
                                spaceAfter=4),
        "subtitle": ParagraphStyle("PGSub", parent=base["Normal"], textColor=colors.grey,
                                   fontSize=10, alignment=1, spaceAfter=10),
        "h2": ParagraphStyle("PGH2", parent=base["Heading2"], textColor=NAVY, fontSize=13,
                             spaceBefore=12, spaceAfter=4),
        "body": ParagraphStyle("PGBody", parent=base["Normal"], fontSize=10, leading=14),
        "small": ParagraphStyle("PGSmall", parent=base["Normal"], fontSize=8.5, leading=12,
                                textColor=colors.HexColor("#444444")),
        "cell": ParagraphStyle("PGCell", parent=base["Normal"], fontSize=9.5, leading=12),
    }


def _bullets(items, style):
    return [Paragraph("- " + escape(str(item)), style) for item in items]


def _kv_table(rows, styles, col_widths=(5.5 * cm, 11 * cm), highlight=None):
    """Two-column key/value table. `highlight` = {row_index: "#hexcolor"} colours a value."""
    highlight = highlight or {}
    data = []
    for i, (k, v) in enumerate(rows):
        value = escape(str(v))
        if i in highlight:
            value = f'<font color="{highlight[i]}"><b>{value}</b></font>'
        data.append([Paragraph(f"<b>{escape(k)}</b>", styles["cell"]),
                     Paragraph(value, styles["cell"])])
    table = Table(data, colWidths=col_widths)
    table.setStyle(TableStyle([
        ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#b0b8c4")),
        ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#eef2f7")),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
    ]))
    return table


def _footer(canvas, doc):
    canvas.saveState()
    canvas.setFont("Helvetica", 8)
    canvas.setFillColor(colors.grey)
    canvas.drawString(2 * cm, 1.2 * cm, "PassGuard - educational password security report (no password stored)")
    canvas.drawRightString(A4[0] - 2 * cm, 1.2 * cm, f"Page {doc.page}")
    canvas.restoreState()


def generate_pdf_report(analysis: dict, policy_result: dict | None = None,
                        comparison: dict | None = None,
                        generated_at: datetime | None = None) -> bytes:
    """
    Create the PDF report and return it as bytes.

    analysis      - dict from analyze_password() (required, must not be empty)
    policy_result - dict from evaluate_policy() (optional)
    comparison    - dict from compare_assessments() (optional)
    """
    if not isinstance(analysis, dict) or "strength" not in analysis:
        raise ValueError("analysis must be a dictionary produced by analyze_password()")
    if analysis.get("is_empty"):
        raise ValueError("Cannot generate a report for an empty password analysis.")

    generated_at = generated_at or datetime.now()
    styles = _styles()
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer, pagesize=A4, leftMargin=2 * cm, rightMargin=2 * cm,
        topMargin=1.8 * cm, bottomMargin=2 * cm,
        title="PassGuard Security Audit Report", author="PassGuard",
        subject="Password assessment (no password stored)", creator="PassGuard",
    )

    story = [
        Paragraph("PassGuard Security Audit Report", styles["title"]),
        Paragraph(f"Generated: {generated_at.strftime('%Y-%m-%d %H:%M:%S')}", styles["subtitle"]),
    ]

    # ---- 1. Summary ------------------------------------------------------- #
    story.append(Paragraph("1. Assessment Summary", styles["h2"]))
    present = [name for name, flag in (
        ("lowercase", analysis["has_lowercase"]), ("uppercase", analysis["has_uppercase"]),
        ("digits", analysis["has_digit"]), ("symbols", analysis["has_symbol"])) if flag]
    rows = [
        ("Strength classification", analysis["strength"]),
        ("Heuristic score", f"{analysis['score']} / 100 (heuristic, not a validated measurement)"),
        ("Password length", f"{analysis['length']} characters"),
        ("Character diversity", f"{analysis['character_types']} of 4 types "
                                f"({', '.join(present) if present else 'none'})"),
        ("Assumed character-set size (N)", analysis["charset_size"]),
        ("Theoretical entropy estimate", f"{analysis['entropy_bits']} bits (H = L x log2(N))"),
    ]
    zx = analysis.get("zxcvbn")
    if zx:
        rows.append(("zxcvbn cross-check", f"score {zx['score']} / 4 (log10 guesses: {zx['guesses_log10']})"))
    strength_color = STRENGTH_COLORS.get(analysis["strength"], "#0b2545")
    story.append(_kv_table(rows, styles, highlight={0: strength_color}))
    if analysis.get("score_cap_reason"):
        story += [Spacer(1, 4), Paragraph(escape(analysis["score_cap_reason"]), styles["small"])]

    # ---- 2. Weaknesses ---------------------------------------------------- #
    story.append(Paragraph("2. Detected Weaknesses", styles["h2"]))
    if analysis["weaknesses"]:
        story += _bullets(analysis["weaknesses"], styles["body"])
    else:
        story.append(Paragraph("No weaknesses were detected by PassGuard's checks. This does not "
                               "prove the password is secure.", styles["body"]))

    # ---- 3. Recommendations ---------------------------------------------- #
    story.append(Paragraph("3. Recommendations", styles["h2"]))
    story += _bullets(analysis["recommendations"], styles["body"])

    section = 4
    # ---- 4. Policy compliance (optional) ---------------------------------- #
    if policy_result:
        story.append(Paragraph(f"{section}. Policy Compliance", styles["h2"]))
        story.append(Paragraph(
            f"Overall result: <b>{'PASS' if policy_result['passed'] else 'FAIL'}</b> "
            f"({policy_result['passed_rules']} of {policy_result['total_rules']} rules satisfied)",
            styles["body"]))
        story.append(Spacer(1, 4))
        data = [["Rule", "Requirement", "Status"]] + [
            [r["rule"], r["requirement"], r["status"]] for r in policy_result["rules"]]
        table = Table(data, colWidths=[4.5 * cm, 9 * cm, 3 * cm])
        style = [
            ("BACKGROUND", (0, 0), (-1, 0), NAVY),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#b0b8c4")),
            ("FONTSIZE", (0, 0), (-1, -1), 9),
        ]
        for i, rule in enumerate(policy_result["rules"], start=1):
            style.append(("TEXTCOLOR", (2, i), (2, i),
                          colors.HexColor("#2e7d32") if rule["satisfied"] else colors.HexColor("#c62828")))
        table.setStyle(TableStyle(style))
        story += [table, Spacer(1, 4), Paragraph(
            "Policy compliance is not the same as password strength: a password can satisfy every "
            "rule and still be predictable.", styles["small"])]
        section += 1

    # ---- 5. Improvement comparison (optional) ----------------------------- #
    if comparison:
        story.append(Paragraph(f"{section}. Improvement Comparison", styles["h2"]))
        story.append(_kv_table([
            ("Strength", f"{comparison['initial_strength']} -> {comparison['latest_strength']}"),
            ("Heuristic score", f"{comparison['initial_score']} -> {comparison['latest_score']} "
                                f"({comparison['score_change']:+d})"),
            ("Entropy (bits)", f"{comparison['initial_entropy']} -> {comparison['latest_entropy']} "
                               f"({comparison['entropy_change']:+.2f})"),
            ("Length", f"{comparison['initial_length']} -> {comparison['latest_length']} "
                       f"({comparison['length_change']:+d})"),
            ("Character types", f"{comparison['initial_character_types']} -> "
                                f"{comparison['latest_character_types']} "
                                f"({comparison['character_types_change']:+d})"),
            ("Weaknesses resolved", "; ".join(comparison["resolved_weaknesses"]) or "None"),
            ("Weaknesses remaining", "; ".join(comparison["remaining_weaknesses"]) or "None"),
            ("New weaknesses", "; ".join(comparison["new_weaknesses"]) or "None"),
        ], styles))
        story += [Spacer(1, 4), Paragraph(escape(comparison["summary"]), styles["small"])]
        section += 1

    # ---- Limitations and privacy ------------------------------------------ #
    story.append(Paragraph(f"{section}. Limitations", styles["h2"]))
    story += _bullets(LIMITATIONS, styles["small"])
    story.append(Paragraph(f"{section + 1}. Privacy Note", styles["h2"]))
    story.append(Paragraph(escape(PRIVACY_NOTE), styles["small"]))

    doc.build(story, onFirstPage=_footer, onLaterPages=_footer)
    return buffer.getvalue()
